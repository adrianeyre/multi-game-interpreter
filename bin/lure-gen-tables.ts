/**
 * Regenerates `src/engine/lure/script/opcodeNames.ts` from ScummVM.
 *
 *   npm run gen:lure-tables -- /path/to/scummvm
 *
 * The third generator of its kind here, after `bin/agos-gen-tables.ts` and
 * `bin/sludge-gen-tables.ts`, and for the reason ADR 0029 gave the first: an
 * opcode name table lives in the interpreter rather than in the game, so it is
 * ours, and a table a person types out is a table with a typo in it. The typo
 * then reads as a decoding fault, which is the most expensive kind of wrong.
 *
 * ScummVM is this project's stated reference for how the originals behave
 * (`README.md`), and its checkout is an argument rather than vendored, for the
 * same reason game data always is.
 *
 * ## What it reads
 *
 * The `S_OPCODE_*` defines in `engines/lure/scripts.h`. Unlike SLUDGE's enum,
 * these carry **explicit values**, so the number is read from the define rather
 * than inferred from declaration order — and the generator checks the set is
 * dense from zero, because a gap would mean an opcode this project would name
 * as the one beside it.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'src/engine/lure/script/opcodeNames.ts';
const SOURCE = join('engines', 'lure', 'scripts.h');

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const checkout = process.argv[2];
if (!checkout) fail('usage: npm run gen:lure-tables -- /path/to/scummvm');

let source: string;
try {
  source = readFileSync(join(checkout, SOURCE), 'utf8');
} catch {
  fail(`could not read ${join(checkout, SOURCE)} — is that a ScummVM checkout?`);
}

const byNumber = new Map<number, string>();
const pattern = /^#define\s+S_OPCODE_([A-Z0-9_]+)\s+(\d+)\s*$/gm;
for (let match = pattern.exec(source); match; match = pattern.exec(source)) {
  const number = Number.parseInt(match[2] as string, 10);
  const existing = byNumber.get(number);
  if (existing !== undefined) {
    fail(`opcode ${number} is defined twice, as ${existing} and ${match[1]}`);
  }
  byNumber.set(number, match[1] as string);
}

if (byNumber.size === 0) fail(`no S_OPCODE_* defines in ${SOURCE}; the format has changed`);

// Dense from zero, or a gap would silently shift every name after it.
const highest = Math.max(...byNumber.keys());
const missing: number[] = [];
for (let number = 0; number <= highest; number += 1) {
  if (!byNumber.has(number)) missing.push(number);
}
if (missing.length > 0) {
  fail(
    `the opcode numbers are not dense from zero — nothing defines ${missing.join(', ')}, so a ` +
      `name table indexed by number would give those slots the wrong name`,
  );
}

/** `NOT_EQUALS` becomes `notEquals`, which is how this codebase spells a name. */
function camel(identifier: string): string {
  const words = identifier.toLowerCase().split('_');
  return words
    .map((word, index) => (index === 0 ? word : word[0]?.toUpperCase() + word.slice(1)))
    .join('');
}

const rows = Array.from({ length: highest + 1 }, (_, number) => {
  return `  /* ${String(number).padStart(2)} */ '${camel(byNumber.get(number) as string)}',`;
}).join('\n');

writeFileSync(
  OUT,
  `/**
 * What each Lure script opcode number is called.
 *
 * **Generated by \`npm run gen:lure-tables\` — do not edit.** The names come
 * from the \`S_OPCODE_*\` defines in \`${SOURCE}\` in a ScummVM checkout, which
 * carry explicit values, so the number is read from the define rather than
 * inferred from order. The generator refuses a set with a gap in it.
 *
 * ${highest + 1} opcodes. The index is the number the bytecode carries, **after
 * the has-parameter bit has been shifted off** — see \`lureScript.ts\`.
 */
export const LURE_OPCODE_NAMES: readonly string[] = [
${rows}
];

/** \`LURE_OPCODE_NAMES.length\`, named for the bound checks that want it. */
export const LURE_OPCODE_COUNT = ${highest + 1};

/** The opcode's name, or a number in angle brackets where there is none. */
export function lureOpcodeName(opcode: number): string {
  return LURE_OPCODE_NAMES[opcode] ?? \`<opcode \${opcode}>\`;
}
`,
  'utf8',
);

process.stdout.write(`${OUT}: ${highest + 1} opcodes\n`);
