/**
 * Regenerates Broken Sword II's opcode-name table from ScummVM.
 *
 *   npm run gen:sword2-tables -- /path/to/scummvm
 *
 * The fifth generator of its kind here. ADR 0029's reason, unchanged: an opcode
 * name lives in the interpreter rather than in the game, so it is ours, and a
 * table a person types out is a table with a typo in it — where the typo then
 * reads as a decoding fault.
 *
 * ## What it reads, and what it does not
 *
 * The `OPCODE(fnX)` entries in `engines/sword2/interpreter.cpp`, in table
 * order: the number a `CP_CALL_MCODE` carries **is** the index.
 *
 * It does **not** read an arity, because there is none to read: Sword2 encodes
 * the parameter count in the instruction beside the opcode number, the same way
 * Sword1 does. That is what makes both families' bytecode splittable without a
 * table, and it is why neither generator emits one.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'src/engine/sword2/script/opcodeNames.ts';
const PARAM_OUT = 'src/engine/sword2/script/opcodeParams.ts';
const SOURCE = join('engines', 'sword2', 'interpreter.cpp');
const PARAM_SOURCE = join('engines', 'sword2', 'function.cpp');

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const checkout = process.argv[2];
if (!checkout) fail('usage: npm run gen:sword2-tables -- /path/to/scummvm');

function read(relative: string): string {
  try {
    return readFileSync(join(checkout as string, relative), 'utf8');
  } catch {
    fail(`could not read ${join(checkout as string, relative)} — is that a ScummVM checkout?`);
  }
}

const source = read(SOURCE);
const functions = read(PARAM_SOURCE);

const start = source.indexOf('void Logic::setupOpcodes()');
if (start < 0) fail('no setupOpcodes in interpreter.cpp; the format has changed');
const end = source.indexOf('\n}', start);
const body = source.slice(start, end);

const names = [...body.matchAll(/OPCODE\((fn[A-Za-z0-9_]+)\)/g)].map((match) => match[1] as string);
if (names.length === 0) fail('no OPCODE entries found; the format has changed');

/**
 * Two entries genuinely name the same function.
 *
 * `fnPrepareMusic` appears twice in the shipped table (at 101 and 103). That is
 * Revolution's, not a parse error, so it is reported rather than deduplicated —
 * collapsing it would renumber every opcode after it.
 */
const duplicates = names
  .map((name, at) => ({ name, at }))
  .filter((entry, _at, all) => all.filter((other) => other.name === entry.name).length > 1);

const file = `/**
 * GENERATED by \`npm run gen:sword2-tables\`. Do not edit by hand.
 *
 * The opcode table: what Broken Sword II's bytecode calls each of its machine
 * code routines. \`CP_CALL_MCODE\` carries the *number*, so the names live in
 * the interpreter rather than in the game — ADR 0029's exact case for a table
 * being ours.
 *
 * No arity column, and deliberately: the parameter count is encoded in the
 * instruction beside the opcode number, so it is read rather than tabled. That
 * is what makes this family's bytecode splittable into editable instructions
 * without a table from outside the game — the same property \`sword1\` has, and
 * the reason Decompilation is available for both.
 *
 * ${
   duplicates.length > 0
     ? `\`${duplicates[0]?.name}\` appears at more than one index (${duplicates
         .map((entry) => entry.at)
         .join(', ')}). That is Revolution's own table and not a parse error, so it is kept:
 * collapsing the repeat would renumber every opcode after it.`
     : 'Every name in the table is distinct.'
 }
 *
 * Read from ScummVM's \`engines/sword2/interpreter.cpp\`.
 */

/** The opcodes, indexed by the number \`CP_CALL_MCODE\` carries. */
export const SWORD2_OPCODE_NAMES: readonly string[] = [
${names.map((name) => `  '${name}',`).join('\n')}
];

/** How many opcodes the table declares. A call above this is a decoding fault. */
export const SWORD2_OPCODE_COUNT = SWORD2_OPCODE_NAMES.length;

/** \`fnWalk\` for 16, or \`opcode<n>\` when the number is outside the table. */
export function sword2OpcodeName(number: number): string {
  return SWORD2_OPCODE_NAMES[number] ?? \`opcode\${number}\`;
}
`;

writeFileSync(OUT, file);

// ---------------------------------------------------------------------------
// The parameter descriptions
// ---------------------------------------------------------------------------

/**
 * What each opcode calls its parameters, read from its own definition.
 *
 * `CP_CALL_MCODE` carries a number and a parameter count, so a disassembler can
 * already say `fnWalk(a, b, c, d, 384, 216, 3)`. What it cannot say is that 384
 * is a target x coordinate — and Revolution wrote that down, in a comment block
 * that opens every one of the hundred and eighteen definitions:
 *
 * ```c
 * int32 Logic::fnWalk(int32 *params) {
 *     // params:  0 pointer to object's logic structure
 *     //          1 pointer to object's graphic structure
 *     …
 *     //          4 target x-coord
 * ```
 *
 * Prose rather than identifiers, which is what Sword1's parameter names are —
 * so this table carries the prose, and the editor shows it as a field label.
 * A description that wraps onto the next comment line is joined back up: the
 * wrap is a column limit in a C file, not a second parameter.
 *
 * `// params:\tnone` is a real entry meaning the opcode takes none, and it
 * parses to an empty row through the same path a wrapped description does —
 * "none" is not a number, so it never opens an entry.
 *
 * Two spellings, because `fnColor` writes `// params\t0: color` where the other
 * hundred and seventeen write `// params:\t0 color`. Both are accepted rather
 * than the block being declared missing, which would silently drop a real
 * description.
 */
function opcodeParams(name: string): string[] {
  const pattern = new RegExp(`^int32 Logic::${name}\\(int32 \\*params\\) \\{`, 'm');
  const match = pattern.exec(functions);
  if (!match) fail(`no definition of ${name} in function.cpp; the format has changed`);
  const body = functions.slice(match.index, functions.indexOf('\n}', match.index));
  const lines = body.split('\n');
  const opens = lines.findIndex((line) => /^\/\/\s*params\b/.test(line.trim()));
  // An opcode that documents no parameters gets an empty row, which is also
  // what `// params:\tnone` produces — the two are the same claim.
  if (opens < 0) return [];

  const comments = [(lines[opens] as string).trim().replace(/^\/\/\s*params:?/, '')];
  for (let at = opens + 1; at < lines.length; at++) {
    const line = (lines[at] as string).trim();
    if (!line.startsWith('//')) break;
    comments.push(line.replace(/^\/\/\t*/, ''));
  }

  const params: string[] = [];
  for (const comment of comments) {
    const entry = /^\t*(\d+)\s*:?\s+(.*)$/.exec(comment);
    if (entry) {
      params.push((entry[2] as string).trim());
    } else if (params.length > 0) {
      params[params.length - 1] = `${params[params.length - 1]} ${comment.trim()}`.trim();
    }
  }
  return params;
}

const paramRows = names.map(opcodeParams);
const described = paramRows.flat().length;

const paramFile = `/**
 * GENERATED by \`npm run gen:sword2-tables\`. Do not edit by hand.
 *
 * What each opcode calls its parameters, so an editor can show a call as named
 * operands rather than as a row of numbers. \`CP_CALL_MCODE\` carries the
 * parameter *count*; what the parameters *mean* lived in Revolution's
 * interpreter, which is ADR 0029's case for a table being ours and generated.
 *
 * These are sentences rather than identifiers, because that is what the source
 * holds — "pointer to object's graphic structure", not \`graphic\`. A row is
 * as long as that opcode takes parameters, so a call with more arguments than
 * its row has names is a call whose count disagrees with ScummVM's comment: the
 * editor says so rather than guessing.
 *
 * ${described} parameters across ${paramRows.length} opcodes are described.
 *
 * Read from the \`// params:\` blocks in ScummVM's \`engines/sword2/function.cpp\`.
 */

/** Opcode number -> what its definition calls each parameter, in push order. */
export const SWORD2_OPCODE_PARAMS: readonly (readonly string[])[] = [
${paramRows
  .map(
    (row) =>
      `  [${row.map((param) => `'${param.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(', ')}],`,
  )
  .join('\n')}
];

/** \`'target x-coord'\` for parameter 4 of \`fnWalk\`, or null where none is given. */
export function sword2OpcodeParamName(opcode: number, index: number): string | null {
  const name = SWORD2_OPCODE_PARAMS[opcode]?.[index];
  return name ? name : null;
}
`;

writeFileSync(PARAM_OUT, paramFile);
// Formatted like every other file here, so a regeneration is not a diff.
execFileSync('npx', ['prettier', '--write', OUT, PARAM_OUT], { stdio: 'inherit' });
process.stdout.write(
  `wrote ${OUT} (${names.length} opcodes) and ${PARAM_OUT} (${described} described parameters)\n`,
);
