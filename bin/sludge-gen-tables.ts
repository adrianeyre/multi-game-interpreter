/**
 * Regenerates `src/engine/sludge/script/commandNames.ts` from ScummVM.
 *
 *   npm run gen:sludge-tables -- /path/to/scummvm
 *
 * ## Why this is a command and not a copy-paste
 *
 * A SLUDGE instruction carries its command as a number and nothing names it.
 * The names live in the interpreter, not in the game, so — exactly like AGOS's
 * argument tables (ADR 0029) — the table is ours rather than the game's, and
 * `bin/agos-gen-tables.ts` settled how this project comes by such a table: it
 * is generated from the reference and re-running the generator is how it gets
 * checked rather than trusted.
 *
 * The stakes are lower here than for AGOS and the discipline is the same for a
 * different reason. AGOS's table decides instruction *lengths*, so one wrong
 * entry misreads every boundary after it. SLUDGE's encoding is fixed-width, so
 * a wrong name cannot desynchronise anything — it just makes a listing lie, and
 * a listing that lies is what somebody reads before writing an interpreter.
 *
 * ScummVM is this project's stated reference for how the originals behave
 * (`README.md`), and its checkout is an argument here rather than vendored,
 * for the same reason game data always is.
 *
 * ## What it reads
 *
 * One enum, `SludgeCommand` in `engines/sludge/csludge.h`. Its declaration
 * order *is* the numbering — the enum has no explicit values — so the order is
 * the whole of the information and a generator that sorted it would destroy the
 * thing it came for.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'src/engine/sludge/script/commandNames.ts';
const SOURCE = join('engines', 'sludge', 'csludge.h');

/** The enum's own terminator, which is a count and not a command. */
const TERMINATOR = 'numSludgeCommands';

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const checkout = process.argv[2];
if (!checkout) {
  fail('usage: npm run gen:sludge-tables -- /path/to/scummvm');
}

let source: string;
try {
  source = readFileSync(join(checkout, SOURCE), 'utf8');
} catch {
  fail(`could not read ${join(checkout, SOURCE)} — is that a ScummVM checkout?`);
}

const body = /enum\s+SludgeCommand\s*\{([^}]*)\}/.exec(source);
if (!body) fail(`no "enum SludgeCommand" in ${SOURCE}`);

// Comments come out of the whole body *before* the split, not after it: the
// enum carries a commented-out entry — `/*SLU_LOAD_SCENE,*/` — whose comma
// splits an entry in half if the strip runs second. Which is what it did, and
// the check below is what caught it rather than a wrong table shipping.
const identifiers = (body[1] as string)
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\/\/.*$/gm, '')
  .split(',')
  .map((entry) => entry.trim())
  .filter((entry) => entry.length > 0);

const terminatorAt = identifiers.indexOf(TERMINATOR);
if (terminatorAt === -1) fail(`the enum does not end with ${TERMINATOR}; the format has changed`);

const commands = identifiers.slice(0, terminatorAt);
for (const identifier of commands) {
  if (!/^SLU_[A-Z0-9_]+$/.test(identifier)) {
    fail(`unexpected enum entry "${identifier}" — the format has changed`);
  }
  if (identifier.includes('=')) {
    fail(`entry "${identifier}" carries an explicit value, so order is no longer the numbering`);
  }
}

/** `SLU_BR_ZERO` becomes `brZero`, which is how this codebase spells a name. */
function camel(identifier: string): string {
  const words = identifier.slice('SLU_'.length).toLowerCase().split('_');
  return words
    .map((word, index) => (index === 0 ? word : word[0]?.toUpperCase() + word.slice(1)))
    .join('');
}

const rows = commands
  .map((identifier, number) => `  /* ${String(number).padStart(2)} */ '${camel(identifier)}',`)
  .join('\n');

writeFileSync(
  OUT,
  `/**
 * What each SLUDGE command number is called.
 *
 * **Generated by \`npm run gen:sludge-tables\` — do not edit.** The names come
 * from \`${SOURCE}\` in a ScummVM checkout, whose enum declares them with no
 * explicit values, so its declaration order is the numbering.
 *
 * ${commands.length} commands. The index is the number the bytecode carries.
 */
export const SLUDGE_COMMAND_NAMES: readonly string[] = [
${rows}
];

/** \`SLUDGE_COMMAND_NAMES.length\`, named for the bound checks that want it. */
export const SLUDGE_COMMAND_COUNT = ${commands.length};

/** The command's name, or a number in angle brackets where there is none. */
export function sludgeCommandName(command: number): string {
  return SLUDGE_COMMAND_NAMES[command] ?? \`<command \${command}>\`;
}
`,
  'utf8',
);

process.stdout.write(`${OUT}: ${commands.length} commands\n`);
