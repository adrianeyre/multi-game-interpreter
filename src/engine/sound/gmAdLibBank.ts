/**
 * A General MIDI instrument bank for the OPL2.
 *
 * An `ADL ` score brings its own instruments, as system-exclusive definitions.
 * A `ROL `, `GMD ` or `MIDI` score brings none: it names programme numbers and
 * expects the synthesiser to own the sounds — a Roland MT-32's patches, or a
 * General MIDI module's. Played on an OPL2 with no bank, every one of those
 * programmes collapsed onto the driver's single default voice, so a piece came
 * out as the right notes on one organ-like tone.
 *
 * This is ScummVM's answer to the same problem, transcribed from
 * `audio/adlib.cpp` (`g_gmInstruments`, `g_gmPercussionInstruments` and
 * `g_gmPercussionInstrumentMap`) — the bank its AdLib driver falls back on for
 * any score that addresses General MIDI programmes. Both projects are GPL.
 *
 * Each row is ScummVM's `AdLibInstrument` in its order — modulator
 * characteristic, level, attack/decay, sustain/release, waveform; the same
 * five for the carrier; feedback — then its `duration`. The bank's effect
 * fields are all zero, so they are left out. They are *not* raw register
 * values — see `fromScummVmBank`, which converts them.
 */
type BankRow = readonly number[];

