/**
 * `rgba` with the gamma table `level` applied, into `target`. Entry 255 is
 * forced to white, which `updateHardware` does for every palette it sends.
 * Answers false (and leaves `target` alone) for a level with no table.
 */
export function applySci32Gamma(
  rgba: ArrayLike<number>,
  target: { [index: number]: number },
  level: number,
): boolean {
  const table = SCI32_GAMMA_TABLES[level];
  if (!table) return false;
  for (let i = 0; i < 256; i++) {
    for (let channel = 0; channel < 3; channel++) {
      target[i * 4 + channel] = table[rgba[i * 4 + channel] ?? 0] ?? 0;
    }
    target[i * 4 + 3] = 255;
  }
  target[255 * 4] = target[255 * 4 + 1] = target[255 * 4 + 2] = 255;
  return true;
}
